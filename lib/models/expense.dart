// =====================================================
// 🧾 Expense Model (Hive)
// =====================================================

import 'package:hive/hive.dart';

part 'expense.g.dart';

@HiveType(typeId: 0)
class Expense extends HiveObject {

  // ---------------------------------------------------
  // 🏷 Title
  // ---------------------------------------------------
  @HiveField(0)
  String title;

  // ---------------------------------------------------
  // 💰 Amount
  // ---------------------------------------------------
  @HiveField(1)
  double amount;

  // ---------------------------------------------------
  // 📂 Category
  // ---------------------------------------------------
  @HiveField(2)
  String category;

  // ---------------------------------------------------
  // 📅 Date
  // ---------------------------------------------------
  @HiveField(3)
  DateTime date;

  // ---------------------------------------------------
  // 🏗 Constructor
  // ---------------------------------------------------
  Expense({
    required this.title,
    required this.amount,
    required this.category,
    required this.date,
  });
}